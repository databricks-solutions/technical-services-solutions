function YamlEditor({ value, onChange }: { value: string; onChange: (v: string) => void }) {
  const gutter = useRef<HTMLPreElement>(null);
  const lines = value.split('\n').length;
  return (
    <div style={{ display: 'flex', border: '1px solid var(--db-border-base)', borderRadius: 4, height: 480 }}>
      <pre
        ref={gutter}
        aria-hidden
        style={{
          ...MONO,
          margin: 0,
          padding: '8px 6px',
          minWidth: 36,
          textAlign: 'right',
          overflow: 'hidden',
          color: 'var(--db-text-subtle)',
          borderRight: '1px solid var(--db-border-base)',
          userSelect: 'none',
        }}
      >
        {Array.from({ length: lines }, (_, i) => i + 1).join('\n')}
      </pre>
      <textarea
        id="gsb-designer-yaml"
        aria-describedby="gsb-designer-issues"
        spellCheck={false}
        value={value}
        wrap="off"
        onChange={(e) => onChange(e.target.value)}
        onScroll={(e) => {
          if (gutter.current) gutter.current.scrollTop = e.currentTarget.scrollTop;
        }}
        style={{
          ...MONO,
          flex: 1,
          padding: 8,
          border: 0,
          resize: 'none',
          background: 'transparent',
          color: 'var(--db-text-base)',
          whiteSpace: 'pre',
          overflow: 'auto',
        }}
      />
    </div>
  );
}

function goToLine(line: number) {
  const el = document.getElementById('gsb-designer-yaml') as HTMLTextAreaElement | null;
  if (!el) return;
  const offset =
    el.value
      .split('\n')
      .slice(0, line - 1)
      .join('\n').length + (line > 1 ? 1 : 0);
  el.focus();
  el.setSelectionRange(offset, offset);
  el.scrollTop = Math.max(0, (line - 4) * 18);
}

function Issues({ issues, live }: { issues: MetricViewIssue[]; live: boolean }) {
  const errors = issues.filter((i) => i.severity === 'error').length;
  return (
    <div
      id="gsb-designer-issues"
      role="status"
      aria-live="polite"
      style={{ display: 'flex', flexDirection: 'column', gap: 4 }}
    >
      <Typography.Text bold>
        {issues.length === 0
          ? 'No issues found.'
          : `${errors} error${errors === 1 ? '' : 's'}, ${issues.length - errors} warning${issues.length - errors === 1 ? '' : 's'}`}
      </Typography.Text>
      {live && (
        <Typography.Text color="secondary">Column and key checks run against the tables when you save.</Typography.Text>
      )}
      {issues.map((i) => (
        <div key={`${i.line ?? 0}-${i.message}`} style={{ display: 'flex', gap: 8, alignItems: 'baseline' }}>
          <Tag componentId="gsb.designer.issue_severity" color={i.severity === 'error' ? 'coral' : 'lemon'}>
            {i.severity === 'error' ? 'Error' : 'Warning'}
          </Tag>
          {i.line ? (
            <Button componentId="gsb.designer.issue_line" type="link" size="small" onClick={() => goToLine(i.line!)}>
              Line {i.line}
            </Button>
          ) : null}
          <Typography.Text>{i.message}</Typography.Text>
        </div>
      ))}
    </div>
  );
}

const RESULT_TAG: Record<TestResult['status'], { color: 'teal' | 'coral'; label: string }> = {
  passed: { color: 'teal', label: 'Passed' },
  failed: { color: 'coral', label: 'Failed' },
  error: { color: 'coral', label: 'Error' },
};

function ValidationResults({ run }: { run: ValidationRun }) {
  const { projectId = '' } = useParams();
  const [confirm, setConfirm] = useState(false);
  const [state, setState] = useState<'idle' | 'busy' | 'removed'>('idle');
  const [error, setError] = useState<string>();
  const remove = () => {
    setState('busy');
    setError(undefined);
    api(`/api/projects/${projectId}/designs/${run.version}/validation/drop`, { statements: run.cleanup }).then(
      () => {
        setState('removed');
        setConfirm(false);
      },
      (err: unknown) => {
        setState('idle');
        setError((err as Error).message);
      }
    );
  };
  return (
    <div style={{ display: 'flex', flexDirection: 'column', gap: 8 }}>
      <div style={{ display: 'flex', gap: 8, alignItems: 'center' }}>
        <Typography.Text bold>Last validation</Typography.Text>
        <Tag
          componentId="gsb.designer.run_status"
          color={run.status === 'passed' ? 'teal' : run.status === 'failed' ? 'coral' : 'lemon'}
        >
          {run.status === 'passed' ? 'All tests passed' : run.status === 'failed' ? 'Failed' : 'Running'}
        </Tag>
        <Typography.Text color="secondary">
          {run.sandboxView}, by {run.createdBy}, {new Date(run.createdAt).toLocaleString()}{' '}
          <OpenInCatalog fullName={run.sandboxView} label="Open the sandbox view" />
        </Typography.Text>
      </div>
      {run.error && <Alert componentId="gsb.designer.run_error" type="error" closable={false} message={run.error} />}
      {run.cleanup.length > 0 && (
        <div style={{ display: 'flex', gap: 8, alignItems: 'center' }}>
          <Button
            componentId="gsb.designer.drop_sandbox"
            size="small"
            disabled={state !== 'idle'}
            onClick={() => setConfirm(true)}
          >
            Remove sandbox view
          </Button>
          {state === 'removed' && (
            <div role="status">
              <Typography.Text color="secondary">Sandbox view removed. Validate again to recreate it.</Typography.Text>
            </div>
          )}
        </div>
      )}
      {error && <Alert componentId="gsb.designer.drop_error" type="error" closable={false} message={error} />}
      <Modal
        componentId="gsb.designer.drop_modal"
        title="Remove sandbox view"
        visible={confirm}
        okText="Run SQL"
        cancelText="Cancel"
        okButtonProps={{ loading: state === 'busy' }}
        onCancel={() => setConfirm(false)}
        onOk={remove}
      >
        <div style={{ display: 'flex', flexDirection: 'column', gap: 12 }}>
          <Alert
            componentId="gsb.designer.drop_warning"
            type="warning"
            closable={false}
            message="This SQL runs as you and drops the sandbox metric view. Source tables and drafts do not change."
          />
          {run.cleanup.map((s) => (
            <SqlBlock key={s} label="SQL to run" sql={s} />
          ))}
        </div>
      </Modal>
      {run.results.map((r) => (
        <details key={r.name} style={{ border: '1px solid var(--db-border-base)', borderRadius: 4, padding: 8 }}>
          <summary style={{ cursor: 'pointer', display: 'flex', gap: 8, alignItems: 'center', flexWrap: 'wrap' }}>
            <Tag componentId="gsb.designer.test_status" color={RESULT_TAG[r.status].color}>
              {RESULT_TAG[r.status].label}
            </Tag>
            <Typography.Text bold>{r.name}</Typography.Text>
            <Typography.Text>{r.detail}</Typography.Text>
          </summary>
          <div style={{ display: 'flex', flexDirection: 'column', gap: 8, marginTop: 8 }}>
            <SqlBlock label="Query on the metric view" sql={r.measureSql} />
            {r.expandedSql && <SqlBlock label="The SQL the engine would produce" sql={r.expandedSql} />}
          </div>
        </details>
      ))}
    </div>
  );
}

function Designer({
  data,
  onChange,
  tab,
  setTab,
}: {
  data: DesignerView & { draft: DesignDraft };
  onChange: (v: DesignerView) => void;
  /** Kept by the page, so a new version (which remounts the designer) stays on the same tab. */
  tab: DesignerTab;
  setTab: (t: DesignerTab) => void;
}) {
  const { projectId = '', parentId = '' } = useParams();
  const navigate = useNavigate();
  const { draft } = data;
  const [yaml, setYaml] = useState(draft.yaml);
  const [instruction, setInstruction] = useState('');
  const [busy, setBusy] = useState<'save' | 'refine' | 'generate' | 'plan' | 'validate'>();
  const [plan, setPlan] = useState<ValidationPlan>();
  const [error, setError] = useState<string>();
  const [editingTests, setEditingTests] = useState(false);
  const dirty = yaml !== draft.yaml;

  const live = useMemo(() => validateMetricView(yaml), [yaml]);
  const saved = useMemo(() => validateMetricView(draft.yaml).view, [draft.yaml]);
  const issues = dirty ? live.issues : draft.issues;
  const view = live.view ?? saved;

  const run = (kind: 'save' | 'refine' | 'generate' | 'validate', path: string, body: unknown, after?: () => void) => {
    setBusy(kind);
    setError(undefined);
    api<DesignerView>(path, body).then(
      (v) => {
        setBusy(undefined);
        after?.();
        setInstruction('');
        setPlan(undefined);
        if (v.draft) setYaml(v.draft.yaml);
        onChange(v);
      },
      (err: unknown) => {
        setBusy(undefined);
        setError((err as Error).message);
      }
    );
  };

  const errors = issues.filter((i) => i.severity === 'error').length;
  const askPlan = () => {
    setBusy('plan');
    setError(undefined);
    api<ValidationPlan>(`/api/projects/${projectId}/designs/${draft.version}/validation`).then(
      (p) => {
        setBusy(undefined);
        setPlan(p);
      },
      (err: unknown) => {
        setBusy(undefined);
        setError((err as Error).message);
      }
    );
  };
  const save = () => run('save', `/api/projects/${projectId}/designs`, { baseVersion: draft.version, yaml });

  // AI help for a saved draft with errors or failed tests. The user can still fix it by hand.
  const savedErrors = draft.issues.filter((i) => i.severity === 'error');
  const failed =
    data.validation?.version === draft.version ? data.validation.results.filter((r) => r.status !== 'passed') : [];
  const aiFix = dirty
    ? undefined
    : savedErrors.length
      ? `Fix these errors in the metric view: ${savedErrors.map((i) => i.message).join('; ')}`
      : failed.length
        ? `These tests failed: ${failed.map((r) => `${r.name}: ${r.detail}`).join('; ')}. Fix the metric view so they pass.`
        : undefined;

  // One clear next action, from the state of the draft.
  const next: { text: string; action?: { label: string; onClick: () => void; disabled?: boolean } } = errors
    ? {
        text: `Fix ${errors} error${errors === 1 ? '' : 's'} in the YAML before you validate.`,
        action: { label: 'Open the YAML', onClick: () => setTab('yaml') },
      }
    : dirty
      ? {
          text: 'You have unsaved changes. Save them as a new version.',
          action: { label: 'Save version', onClick: save },
        }
      : draft.status !== 'validated'
        ? {
            text: `Validate the design: ${draft.tests.length} test${draft.tests.length === 1 ? '' : 's'} run in the sandbox as you.`,
            action: { label: 'Validate in sandbox', onClick: askPlan, disabled: !draft.tests.length },
          }
        : {
            text: 'Validated. Optimize it if you want (stress test, materialization, Genie), then publish it.',
            action: {
              label: 'Next: Optimize',
              onClick: () => void navigate(`/projects/${parentId}/sub/${projectId}/optimize`),
            },
          };

  return (
    <div style={{ display: 'flex', flexDirection: 'column', gap: 16 }}>
      <div style={{ display: 'flex', alignItems: 'center', gap: 8, flexWrap: 'wrap' }}>
        <Typography.Title level={3} withoutMargins>
          {draft.name}
        </Typography.Title>
        <Tag componentId="gsb.designer.version">Version {draft.version}</Tag>
        <Tag componentId="gsb.designer.origin">{ORIGIN[draft.origin]}</Tag>
        <Tag componentId="gsb.designer.status" color={draft.status === 'validated' ? 'teal' : 'lemon'}>
          {draft.status === 'validated' ? 'Validated' : 'Not validated'}
        </Tag>
        {dirty && <Tag componentId="gsb.designer.dirty">Unsaved changes</Tag>}
      </div>

      <div
        role="status"
        style={{
          display: 'flex',
          alignItems: 'center',
          justifyContent: 'space-between',
          gap: 12,
          padding: 12,
          borderRadius: 8,
          background: 'var(--db-surface-subtle)',
          flexWrap: 'wrap',
        }}
      >
        <div>
          <Typography.Text bold>Next: </Typography.Text>
          <Typography.Text>{next.text}</Typography.Text>
        </div>
        {next.action && (
          <Button
            componentId="gsb.designer.next"
            type="primary"
            loading={busy === 'save' || busy === 'plan' || busy === 'validate'}
            disabled={!!busy || next.action.disabled}
            onClick={next.action.onClick}
          >
            {next.action.label}
          </Button>
        )}
        {aiFix && (
          <Button
            componentId="gsb.designer.ai_fix"
            loading={busy === 'refine'}
            disabled={!!busy}
            onClick={() =>
              run('refine', `/api/projects/${projectId}/designs/refine`, { instruction: aiFix.slice(0, 2000) })
            }
          >
            Fix with AI
          </Button>
        )}
      </div>

      {draft.origin !== 'edited' && (
        <Alert
          componentId="gsb.designer.ai_notice"
          type="info"
          closable={false}
          message="Designed by AI. Review the joins and every measure before you validate."
          description={draft.explanations.summary}
        />
      )}
      {error && <Alert componentId="gsb.designer.error" type="error" closable={false} message={error} />}

      <Tabs.Root componentId="gsb.designer.tabs" value={tab} onValueChange={(v) => setTab(v as DesignerTab)}>
        <Tabs.List>
          <Tabs.Trigger value="model">Model</Tabs.Trigger>
          <Tabs.Trigger value="yaml">YAML{errors ? ` (${errors} errors)` : dirty ? ' (unsaved)' : ''}</Tabs.Trigger>
          <Tabs.Trigger value="tests">Tests ({draft.tests.length})</Tabs.Trigger>
          <Tabs.Trigger value="history">History ({data.history.length})</Tabs.Trigger>
        </Tabs.List>

        <Tabs.Content value="model">
          <div style={{ display: 'flex', flexDirection: 'column', gap: 16, paddingTop: 16 }}>
            {view ? (
              <>
                <section
                  aria-labelledby="gsb-designer-joins"
                  style={{ display: 'flex', flexDirection: 'column', gap: 8 }}
                >
                  <Typography.Title level={4} id="gsb-designer-joins" withoutMargins>
                    Joins
                  </Typography.Title>
                  <JoinDiagram view={view} issues={issues} />
                </section>
                <FieldTables
                  projectId={projectId}
                  view={view}
                  explanations={draft.explanations}
                  disabled={dirty || !!busy}
                  saving={busy === 'save'}
                  onSave={(y) =>
                    run('save', `/api/projects/${projectId}/designs`, { baseVersion: draft.version, yaml: y })
                  }
                />
              </>
            ) : (
              <Typography.Text color="secondary">Fix the YAML errors to see the model.</Typography.Text>
            )}
            <div style={{ display: 'flex', flexDirection: 'column', gap: 8, maxWidth: 720 }}>
              <FormUI.Label htmlFor="gsb-designer-refine">Ask the AI for a change</FormUI.Label>
              <Input.TextArea
                componentId="gsb.designer.refine_input"
                id="gsb-designer-refine"
                value={instruction}
                autoSize={{ minRows: 2, maxRows: 6 }}
                placeholder="For example: add a gross margin measure and a ship year dimension."
                onChange={(e) => setInstruction(e.target.value)}
              />
              {dirty && <FormUI.Hint>Save or discard your edits before you ask the AI for a change.</FormUI.Hint>}
              <div style={{ display: 'flex', gap: 8 }}>
                <Button
                  componentId="gsb.designer.refine"
                  loading={busy === 'refine'}
                  disabled={dirty || instruction.trim().length < 3 || !!busy}
                  onClick={() => run('refine', `/api/projects/${projectId}/designs/refine`, { instruction })}
                >
                  Apply change
                </Button>
                <Button
                  componentId="gsb.designer.regenerate"
                  loading={busy === 'generate'}
                  disabled={dirty || !!busy}
                  onClick={() => run('generate', `/api/projects/${projectId}/designs/generate`, {})}
                >
                  Generate a new design
                </Button>
                <Button
                  componentId="gsb.designer.retemplate"
                  disabled={dirty || !!busy}
                  onClick={() => run('save', `/api/projects/${projectId}/designs/template`, {})}
                >
                  Start from a template
                </Button>
                <Button
                  componentId="gsb.designer.patterns"
                  disabled={dirty || !!busy}
                  onClick={() => void navigate(`/projects/${parentId}/sub/${projectId}/patterns`)}
                >
                  Start from a pattern
                </Button>
              </div>
              {(busy === 'refine' || busy === 'generate') && (
                <div role="status">
                  <Typography.Text color="secondary">
                    Reading the tables and designing. This can take a minute.
                  </Typography.Text>
                </div>
              )}
            </div>
          </div>
        </Tabs.Content>

        <Tabs.Content value="yaml">
          <section
            aria-labelledby="gsb-designer-yaml-label"
            style={{ display: 'flex', flexDirection: 'column', gap: 8, paddingTop: 16 }}
          >
            <FormUI.Label htmlFor="gsb-designer-yaml" id="gsb-designer-yaml-label">
              Metric view YAML
            </FormUI.Label>
            <YamlEditor value={yaml} onChange={setYaml} />
            <div style={{ display: 'flex', gap: 8 }}>
              <Button
                componentId="gsb.designer.save"
                type="primary"
                loading={busy === 'save'}
                disabled={!dirty || !!busy}
                onClick={save}
              >
                Save version
              </Button>
              <Button
                componentId="gsb.designer.discard"
                disabled={!dirty || !!busy}
                onClick={() => setYaml(draft.yaml)}
              >
                Discard changes
              </Button>
            </div>
            <Issues issues={issues} live={dirty} />
          </section>
        </Tabs.Content>

        <Tabs.Content value="tests">
          <section style={{ display: 'flex', flexDirection: 'column', gap: 8, paddingTop: 16 }}>
            <Typography.Text color="secondary">
              Validation creates the metric view in the sandbox schema, runs each test as you, and compares the result
              with plain SQL derived from the YAML.
            </Typography.Text>
            {editingTests && saved ? (
              <TestEditor
                tests={draft.tests}
                view={saved}
                saving={busy === 'save'}
                onCancel={() => setEditingTests(false)}
                onSave={(tests) =>
                  run(
                    'save',
                    `/api/projects/${projectId}/designs`,
                    { baseVersion: draft.version, yaml: draft.yaml, tests },
                    () => setEditingTests(false)
                  )
                }
              />
            ) : (
              <>
                {draft.tests.length ? (
                  <ul style={{ margin: 0, paddingLeft: 20 }}>
                    {draft.tests.map((t) => (
                      <li key={t.name}>
                        <Typography.Text bold>{t.name}</Typography.Text>: {t.measures.join(', ')}
                        {t.dimensions.length ? ` by ${t.dimensions.join(', ')}` : ' in total'}
                      </li>
                    ))}
                  </ul>
                ) : (
                  <Typography.Text>No test cases match the current fields.</Typography.Text>
                )}
                <div>
                  <Button
                    componentId="gsb.designer.edit_tests"
                    disabled={dirty || !!busy || !saved}
                    onClick={() => setEditingTests(true)}
                  >
                    Edit tests by hand
                  </Button>
                </div>
              </>
            )}
            <div>
              <Button
                componentId="gsb.designer.validate"
                type="primary"
                loading={busy === 'plan' || busy === 'validate'}
                disabled={dirty || !!busy || !draft.tests.length || draft.issues.some((i) => i.severity === 'error')}
                onClick={askPlan}
              >
                Validate in sandbox
              </Button>
            </div>
            {busy === 'validate' && (
              <div role="status">
                <Typography.Text color="secondary">Creating the sandbox view and running the tests.</Typography.Text>
              </div>
            )}
            {data.validation && <ValidationResults run={data.validation} />}
          </section>
        </Tabs.Content>

        <Tabs.Content value="history">
          <History
            projectId={projectId}
            history={data.history}
            current={draft.version}
            busy={!!busy}
            onRestore={(v) => run('save', `/api/projects/${projectId}/designs/${v}/restore`, {})}
          />
        </Tabs.Content>
      </Tabs.Root>

      <Modal
        componentId="gsb.designer.validate_modal"
        title="Validate in sandbox"
        visible={!!plan}
        okText="Run SQL"
        cancelText="Cancel"
        okButtonProps={{ loading: busy === 'validate' }}
        onCancel={() => setPlan(undefined)}
        onOk={() => {
          if (plan)
            run('validate', `/api/projects/${projectId}/designs/${draft.version}/validation`, {
              statements: plan.statements,
            });
        }}
      >
        {plan && (
          <div style={{ display: 'flex', flexDirection: 'column', gap: 12 }}>
            <Alert
              componentId="gsb.designer.validate_warning"
              type="warning"
              closable={false}
              message={`This SQL runs as you and creates or replaces the metric view ${plan.sandboxView}. Then ${draft.tests.length} read-only test queries run. Result values are not stored.`}
            />
            {plan.statements.map((s) => (
              <SqlBlock key={s} label="SQL to run" sql={s} />
            ))}
          </div>
        )}
      </Modal>
    </div>
  );
}

type DesignerTab = 'model' | 'yaml' | 'tests' | 'history';
const DESIGNER_TABS: DesignerTab[] = ['model', 'yaml', 'tests', 'history'];

function VersionYaml({
  projectId,
  version,
  current,
  busy,
  onRestore,
}: {
  projectId: string;
  version: number;
  current: number;
  busy: boolean;
  onRestore: (version: number) => void;
}) {
  const res = useResource<DesignerView>(`/api/projects/${projectId}/designs?version=${version}`);
  const shown = res.data?.draft;
  return (
    <DataState status={res.status} message={res.error} onRetry={res.reload}>
      {shown && (
        <div style={{ display: 'flex', flexDirection: 'column', gap: 8 }}>
          <SqlBlock label={`Version ${shown.version} YAML (read-only)`} sql={shown.yaml} />
          {shown.version !== current && (
            <div>
              <Button componentId="gsb.designer.restore" disabled={busy} onClick={() => onRestore(version)}>
                Restore as a new version
              </Button>
            </div>
          )}
        </div>
      )}
    </DataState>
  );
}

/** Every version, newest first. A version opens read-only; Restore copies it as a new version, validated if it was. */
function History({
  projectId,
  history,
  current,
  busy,
  onRestore,
}: {
  projectId: string;
  history: DesignerView['history'];
  current: number;
  busy: boolean;
  onRestore: (version: number) => void;
}) {
  const [open, setOpen] = useState<number>();
  return (
    <div style={{ display: 'flex', flexDirection: 'column', gap: 12, paddingTop: 16 }}>
      <Table>
        <TableRow isHeader>
          <TableHeader componentId="gsb.designer.h_version">Version</TableHeader>
          <TableHeader componentId="gsb.designer.h_origin">Change</TableHeader>
          <TableHeader componentId="gsb.designer.h_status">Status</TableHeader>
          <TableHeader componentId="gsb.designer.h_by">By</TableHeader>
          <TableHeader componentId="gsb.designer.h_when">When</TableHeader>
          <TableHeader componentId="gsb.designer.h_view">View</TableHeader>
        </TableRow>
        {[...history]
          .sort((a, b) => b.version - a.version)
          .map((h) => (
            <TableRow key={h.version}>
              <TableCell>
                {h.version}
                {h.version === current ? ' (current)' : ''}
              </TableCell>
              <TableCell>{ORIGIN[h.origin]}</TableCell>
              <TableCell>{h.status === 'validated' ? 'Validated' : 'Not validated'}</TableCell>
              <TableCell>{h.createdBy}</TableCell>
              <TableCell>{new Date(h.createdAt).toLocaleString()}</TableCell>
              <TableCell>
                <Button
                  componentId="gsb.designer.h_open"
                  size="small"
                  type="tertiary"
                  onClick={() => setOpen(open === h.version ? undefined : h.version)}
                >
                  {open === h.version ? 'Close' : 'Open'}
                </Button>
              </TableCell>
            </TableRow>
          ))}
      </Table>
      {open && (
        <VersionYaml
          key={open}
          projectId={projectId}
          version={open}
          current={current}
          busy={busy}
          onRestore={onRestore}
        />
      )}
    </div>
  );
}

export function DesignerPage() {
  const { projectId = '', parentId = '' } = useParams();
  const navigate = useNavigate();
  const view = useResource<DesignerView>(`/api/projects/${projectId}/designs`);
  const [tab, setTab] = useTab(DESIGNER_TABS, 'model');
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string>();
  const data = view.data;

  const start = (how: 'generate' | 'template') => {
    setBusy(true);
    setError(undefined);
    api<DesignerView>(`/api/projects/${projectId}/designs/${how}`, {}).then(
      (v) => {
        setBusy(false);
        view.setData(v);
      },
      (err: unknown) => {
        setBusy(false);
        setError((err as Error).message);
      }
    );
  };

  return (
    <DataState status={view.status} message={view.error} onRetry={view.reload}>
      {data?.draft ? (
        <Designer
          key={data.draft.version}
          data={{ ...data, draft: data.draft }}
          onChange={view.setData}
          tab={tab}
          setTab={setTab}
        />
      ) : (
        <div style={{ display: 'flex', flexDirection: 'column', gap: 12, alignItems: 'center' }}>
          <Empty
            title="No metric view yet"
            description="The AI designs a metric view from the confirmed brief and the profiled source tables. It reads metadata only, with your permissions. Or start from the template, with no AI, and edit the YAML yourself."
            button={
              <div style={{ display: 'flex', gap: 8 }}>
                <Button
                  componentId="gsb.designer.generate"
                  type="primary"
                  loading={busy}
                  onClick={() => start('generate')}
                >
                  Generate design
                </Button>
                <Button componentId="gsb.designer.template" disabled={busy} onClick={() => start('template')}>
                  Start from a template
                </Button>
                <Button
                  componentId="gsb.designer.empty_patterns"
                  disabled={busy}
                  onClick={() => void navigate(`/projects/${parentId}/sub/${projectId}/patterns`)}
                >
                  Start from a pattern
                </Button>
              </div>
            }
          />
          {busy && (
            <div role="status">
              <Typography.Text color="secondary">
                Reading the tables and designing. This can take a minute.
              </Typography.Text>
            </div>
          )}
          {error && <Alert componentId="gsb.designer.error" type="error" closable={false} message={error} />}
        </div>
      )}
    </DataState>
  );
}
