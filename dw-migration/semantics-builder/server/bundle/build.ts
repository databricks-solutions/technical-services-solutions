import type { TestCase } from '../../shared/designer';
import type { MetricView } from '../../shared/metricView';
import { quoteId, quoteName } from '../readiness/profile';
import { createStatement, literal, measureQuery } from '../designer/validate';

/**
 * A Declarative Automation Bundle for one promoted metric view, for CI/CD in the customer's own Git and pipeline:
 * a deploy job (create the view, then run its tests) and a nightly check job (the view exists as a metric view, its
 * fields are the exported ones, and the tests pass). Every task is a SQL file on a SQL warehouse; a failing check
 * raises an error with assert_true, so the job fails and emails the owner. The values in the tests are the expected
 * values that the user typed; no query result goes into the bundle.
 */

export interface BundleInput {
  /** catalog.schema.view in Unity Catalog. */
  target: string;
  yaml: string;
  view: MetricView;
  tests: TestCase[];
  version: number;
  project: string;
  subProject: string;
}

const slug = (s: string) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9_]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .slice(0, 60) || 'metric_view';

/** A test as one SQL statement: an expected value test asserts its tolerance, a query test only has to run. */
export function testStatement(target: string, t: TestCase): string {
  const label = `Test "${t.name}"`.replace(/'/g, '');
  if (!t.expect) return `-- ${label}\n${measureQuery(target, t)};`;
  const m = `MEASURE(${quoteId(t.measures[0])})`;
  const where = t.expect.filters.map((f) => `${quoteId(f.dimension)} = ${literal(f.value)}`);
  const check =
    t.expect.value === 0
      ? `${m} = 0`
      : `abs(${m} - ${t.expect.value}) <= abs(${t.expect.value}) * ${t.expect.tolerancePct} / 100`;
  const message = literal(
    t.expect.value === 0
      ? `${label}: ${t.measures[0]} is not 0.`
      : `${label}: ${t.measures[0]} is outside ${t.expect.tolerancePct}% of the expected value.`
  );
  return `-- ${label}\nSELECT assert_true(${check}, ${message}) FROM ${quoteName(target)}${where.length ? ` WHERE ${where.join(' AND ')}` : ''};`;
}

/** The view exists as a metric view, and its fields are the exported ones (a change outside the bundle fails). */
export function driftStatements(target: string, view: MetricView, version: number): string {
  const [catalog, schema, name] = target.split('.');
  const fields = [...view.dimensions, ...view.measures].map((f) => f.name.toLowerCase()).sort();
  const where = `table_schema = ${literal(schema.toLowerCase())} AND table_name = ${literal(name.toLowerCase())}`;
  return [
    `-- The view exists, as a metric view.`,
    `SELECT assert_true(count(*) = 1, ${literal(`${target} is not a metric view in Unity Catalog.`)})`,
    `FROM ${quoteId(catalog)}.information_schema.tables WHERE ${where} AND table_type = 'METRIC_VIEW';`,
    ``,
    `-- Its fields are the ones of version ${version}. A field added, removed or renamed outside the bundle fails.`,
    `SELECT assert_true(`,
    `  coalesce(array_join(array_sort(collect_list(lower(column_name))), ','), '') = ${literal(fields.join(','))},`,
    `  ${literal(`The fields of ${target} changed outside the bundle.`)}`,
    `) FROM ${quoteId(catalog)}.information_schema.columns WHERE ${where};`,
  ].join('\n');
}

export function bundleFiles(b: BundleInput): Record<string, string> {
  const name = slug(b.target.split('.').pop() ?? b.subProject);
  const from = `${b.project} / ${b.subProject}, version ${b.version}`;
  const tests = b.tests.length
    ? b.tests.map((t) => testStatement(b.target, t)).join('\n\n')
    : `-- No tests in version ${b.version}.\nSELECT 1;`;
  const sqlTask = (file: string) => [
    `          sql_task:`,
    `            warehouse_id: \${var.warehouse_id}`,
    `            file:`,
    `              path: ../src/${file}`,
  ];
  return {
    'databricks.yml': [
      `# Generated by STS Semantics Builder from ${from}.`,
      `bundle:`,
      `  name: ${name}_metric_view`,
      ``,
      `include:`,
      `  - resources/*.yml`,
      ``,
      `variables:`,
      `  warehouse_id:`,
      `    description: The SQL warehouse that runs the SQL files.`,
      `  owner_email:`,
      `    description: The email address that gets a message when a job fails.`,
      ``,
      `targets:`,
      `  dev:`,
      `    default: true`,
      `    mode: development`,
      `  prod:`,
      `    mode: production`,
      `    workspace:`,
      `      # One copy for production, under the identity that deploys it (a CI service principal).`,
      `      root_path: /Workspace/Users/\${workspace.current_user.userName}/.bundle/\${bundle.name}/\${bundle.target}`,
      ``,
    ].join('\n'),
    [`resources/${name}_deploy.job.yml`]: [
      `resources:`,
      `  jobs:`,
      `    ${name}_deploy:`,
      `      name: Deploy ${b.target}`,
      `      email_notifications:`,
      `        on_failure:`,
      `          - \${var.owner_email}`,
      `      tasks:`,
      `        - task_key: create_view`,
      ...sqlTask('create_view.sql'),
      `        - task_key: tests`,
      `          depends_on:`,
      `            - task_key: create_view`,
      ...sqlTask('tests.sql'),
      ``,
    ].join('\n'),
    [`resources/${name}_nightly_check.job.yml`]: [
      `resources:`,
      `  jobs:`,
      `    ${name}_nightly_check:`,
      `      name: Nightly check of ${b.target}`,
      `      schedule:`,
      `        quartz_cron_expression: '0 0 2 * * ?'`,
      `        timezone_id: UTC`,
      `      email_notifications:`,
      `        on_failure:`,
      `          - \${var.owner_email}`,
      `      tasks:`,
      `        - task_key: drift`,
      ...sqlTask('drift.sql'),
      `        - task_key: tests`,
      ...sqlTask('tests.sql'),
      ``,
    ].join('\n'),
    'src/create_view.sql': `-- ${b.target}, from ${from}.\n${createStatement(b.target, b.yaml)};\n`,
    'src/tests.sql': `-- The tests of ${from}. A failing expected value test stops the job.\n\n${tests}\n`,
    'src/drift.sql': `${driftStatements(b.target, b.view, b.version)}\n`,
    'README.md': [
      `# ${b.target}`,
      ``,
      `A Declarative Automation Bundle for the metric view \`${b.target}\`, generated by STS Semantics Builder from`,
      `${from}. Keep it in Git and deploy it from your pipeline.`,
      ``,
      `- \`src/create_view.sql\` creates or replaces the view with the YAML of version ${b.version}.`,
      `- \`src/tests.sql\` runs the ${b.tests.length} test(s) of that version. An expected value test fails the task when`,
      `  the measure is outside its tolerance.`,
      `- \`src/drift.sql\` checks that the view is a metric view and that its fields are the ones of version ${b.version}.`,
      `- The job \`${name}_deploy\` creates the view, then runs the tests.`,
      `- The job \`${name}_nightly_check\` runs the drift check and the tests every night at 02:00 UTC, and emails`,
      `  \`owner_email\` when one fails. In the \`dev\` target its schedule is paused (development mode).`,
      ``,
      `## Deploy`,
      ``,
      '```sh',
      `databricks bundle validate --target dev --var warehouse_id=<warehouse-id> --var owner_email=<you@example.com>`,
      `databricks bundle deploy --target dev --var warehouse_id=<warehouse-id> --var owner_email=<you@example.com>`,
      `databricks bundle run ${name}_deploy --target dev --var warehouse_id=<warehouse-id> --var owner_email=<you@example.com>`,
      '```',
      ``,
      `For another environment, change the view name in \`src/*.sql\` (or keep one bundle per environment), and use`,
      `\`--target prod\`. The jobs run as the identity that deploys the bundle, which needs \`CREATE TABLE\` on the`,
      `schema, \`SELECT\` on the source tables, and \`CAN USE\` on the warehouse.`,
      ``,
    ].join('\n'),
  };
}
