const MONO = { fontFamily: 'ui-monospace, SFMono-Regular, Menlo, monospace', fontSize: 12, lineHeight: '18px' };

const ADDITIVITY: Record<Additivity, string> = {
  additive: 'Additive',
  semi_additive: 'Semi-additive',
  non_additive: 'Not additive',
  ratio: 'Ratio',
};

const ORIGIN: Record<DesignDraft['origin'], string> = {
  generated: 'Generated by AI',
  refined: 'Changed by AI',
  edited: 'Edited',
};

function YamlEditor({ value, onChange }: { value: string; onChange: (v: string) => void }) {
  const gutter = useRef<HTMLPreElement>(null);
  const lines = value.split('\n').length;
  return (
    <div style={{ display: 'flex', border: '1px solid var(--db-border-base)', borderRadius: 4, height: 480 }}>
      <pre
        ref={gutter}
        aria-hidden
        style={{
          ...MONO,
          margin: 0,
          padding: '8px 6px',
          minWidth: 36,
          textAlign: 'right',
          overflow: 'hidden',
          color: 'var(--db-text-subtle)',
          borderRight: '1px solid var(--db-border-base)',
          userSelect: 'none',
        }}
      >
        {Array.from({ length: lines }, (_, i) => i + 1).join('\n')}
      </pre>
      <textarea
        id="gsb-designer-yaml"
        aria-describedby="gsb-designer-issues"
        spellCheck={false}
        value={value}
        wrap="off"
        onChange={(e) => onChange(e.target.value)}
        onScroll={(e) => {
          if (gutter.current) gutter.current.scrollTop = e.currentTarget.scrollTop;
        }}
        style={{
          ...MONO,
          flex: 1,
          padding: 8,
          border: 0,
          resize: 'none',
          background: 'transparent',
          color: 'var(--db-text-base)',
          whiteSpace: 'pre',
          overflow: 'auto',
        }}
      />
    </div>
  );
}

function goToLine(line: number) {
  const el = document.getElementById('gsb-designer-yaml') as HTMLTextAreaElement | null;
  if (!el) return;
  const offset =
    el.value
      .split('\n')
      .slice(0, line - 1)
      .join('\n').length + (line > 1 ? 1 : 0);
  el.focus();
  el.setSelectionRange(offset, offset);
  el.scrollTop = Math.max(0, (line - 4) * 18);
}

function Issues({ issues, live }: { issues: MetricViewIssue[]; live: boolean }) {
  const errors = issues.filter((i) => i.severity === 'error').length;
  return (
    <div
      id="gsb-designer-issues"
      role="status"
      aria-live="polite"
      style={{ display: 'flex', flexDirection: 'column', gap: 4 }}
    >
      <Typography.Text bold>
        {issues.length === 0
          ? 'No issues found.'
          : `${errors} error${errors === 1 ? '' : 's'}, ${issues.length - errors} warning${issues.length - errors === 1 ? '' : 's'}`}
      </Typography.Text>
      {live && (
        <Typography.Text color="secondary">Column and key checks run against the tables when you save.</Typography.Text>
      )}
      {issues.map((i) => (
        <div key={`${i.line ?? 0}-${i.message}`} style={{ display: 'flex', gap: 8, alignItems: 'baseline' }}>
          <Tag componentId="gsb.designer.issue_severity" color={i.severity === 'error' ? 'coral' : 'lemon'}>
            {i.severity === 'error' ? 'Error' : 'Warning'}
          </Tag>
          {i.line ? (
            <Button componentId="gsb.designer.issue_line" type="link" size="small" onClick={() => goToLine(i.line!)}>
              Line {i.line}
            </Button>
          ) : null}
          <Typography.Text>{i.message}</Typography.Text>
        </div>
      ))}
    </div>
  );
}

function Fields({
  draft,
  view,
}: {
  draft: DesignDraft;
  view: NonNullable<ReturnType<typeof validateMetricView>['view']>;
}) {
  const explain = draft.explanations;
  return (
    <>
      <Typography.Title level={4} withoutMargins>
        Measures
      </Typography.Title>
      <Table>
        <TableRow isHeader>
          <TableHeader componentId="gsb.designer.m_name">Name</TableHeader>
          <TableHeader componentId="gsb.designer.m_kind">Type</TableHeader>
          <TableHeader componentId="gsb.designer.m_explain">How it is computed</TableHeader>
        </TableRow>
        {view.measures.map((m) => {
          const e = explain.measures[m.name];
          return (
            <TableRow key={m.name}>
              <TableCell>{m.display_name ?? m.name}</TableCell>
              <TableCell>{e ? ADDITIVITY[e.additivity] : '-'}</TableCell>
              <TableCell multiline>
                <div style={{ display: 'flex', flexDirection: 'column', gap: 2 }}>
                  <span>{e?.explanation ?? m.comment ?? 'No explanation yet.'}</span>
                  <code style={{ ...MONO, color: 'var(--db-text-subtle)' }}>{m.expr}</code>
                </div>
              </TableCell>
            </TableRow>
          );
        })}
      </Table>
      <Typography.Title level={4} withoutMargins>
        Dimensions
      </Typography.Title>
      <Table>
        <TableRow isHeader>
          <TableHeader componentId="gsb.designer.d_name">Name</TableHeader>
          <TableHeader componentId="gsb.designer.d_explain">How it is computed</TableHeader>
        </TableRow>
        {view.dimensions.map((d) => (
          <TableRow key={d.name}>
            <TableCell>{d.display_name ?? d.name}</TableCell>
            <TableCell multiline>
              <div style={{ display: 'flex', flexDirection: 'column', gap: 2 }}>
                <span>{explain.dimensions[d.name]?.explanation ?? d.comment ?? 'No explanation yet.'}</span>
                <code style={{ ...MONO, color: 'var(--db-text-subtle)' }}>{d.expr}</code>
              </div>
            </TableCell>
          </TableRow>
        ))}
      </Table>
    </>
  );
}

const RESULT_TAG: Record<TestResult['status'], { color: 'teal' | 'coral'; label: string }> = {
  passed: { color: 'teal', label: 'Passed' },
  failed: { color: 'coral', label: 'Failed' },
  error: { color: 'coral', label: 'Error' },
};

function SqlBlock({ label, sql }: { label: string; sql: string }) {
  return (
    <div style={{ display: 'flex', flexDirection: 'column', gap: 4 }}>
      <Typography.Text bold>{label}</Typography.Text>
      <pre
        style={{
          ...MONO,
          margin: 0,
          padding: 12,
          maxHeight: 320,
          overflow: 'auto',
          whiteSpace: 'pre-wrap',
          wordBreak: 'break-word',
          border: '1px solid var(--db-border-base)',
          borderRadius: 4,
        }}
      >
        {sql}
      </pre>
    </div>
  );
}

function ValidationResults({ run }: { run: ValidationRun }) {
  const { projectId = '' } = useParams();
  const [confirm, setConfirm] = useState(false);
  const [state, setState] = useState<'idle' | 'busy' | 'removed'>('idle');
  const [error, setError] = useState<string>();
  const remove = () => {
    setState('busy');
    setError(undefined);
    api(`/api/projects/${projectId}/designs/${run.version}/validation/drop`, { statements: run.cleanup }).then(
      () => {
        setState('removed');
        setConfirm(false);
      },
      (err: unknown) => {
        setState('idle');
        setError((err as Error).message);
      }
    );
  };
  return (
    <div style={{ display: 'flex', flexDirection: 'column', gap: 8 }}>
      <div style={{ display: 'flex', gap: 8, alignItems: 'center' }}>
        <Typography.Text bold>Last validation</Typography.Text>
        <Tag
          componentId="gsb.designer.run_status"
          color={run.status === 'passed' ? 'teal' : run.status === 'failed' ? 'coral' : 'lemon'}
        >
          {run.status === 'passed' ? 'All tests passed' : run.status === 'failed' ? 'Failed' : 'Running'}
        </Tag>
        <Typography.Text color="secondary">
          {run.sandboxView}, by {run.createdBy}, {new Date(run.createdAt).toLocaleString()}
        </Typography.Text>
      </div>
      {run.error && <Alert componentId="gsb.designer.run_error" type="error" closable={false} message={run.error} />}
      {run.cleanup.length > 0 && (
        <div style={{ display: 'flex', gap: 8, alignItems: 'center' }}>
          <Button
            componentId="gsb.designer.drop_sandbox"
            size="small"
            disabled={state !== 'idle'}
            onClick={() => setConfirm(true)}
          >
            Remove sandbox view
          </Button>
          {state === 'removed' && (
            <div role="status">
              <Typography.Text color="secondary">Sandbox view removed. Validate again to recreate it.</Typography.Text>
            </div>
          )}
        </div>
      )}
      {error && <Alert componentId="gsb.designer.drop_error" type="error" closable={false} message={error} />}
      <Modal
        componentId="gsb.designer.drop_modal"
        title="Remove sandbox view"
        visible={confirm}
        okText="Run SQL"
        cancelText="Cancel"
        okButtonProps={{ loading: state === 'busy' }}
        onCancel={() => setConfirm(false)}
        onOk={remove}
      >
        <div style={{ display: 'flex', flexDirection: 'column', gap: 12 }}>
          <Alert
            componentId="gsb.designer.drop_warning"
            type="warning"
            closable={false}
            message="This SQL runs as you and drops the sandbox metric view. Source tables and drafts do not change."
          />
          {run.cleanup.map((s) => (
            <SqlBlock key={s} label="SQL to run" sql={s} />
          ))}
        </div>
      </Modal>
      {run.results.map((r) => (
        <details key={r.name} style={{ border: '1px solid var(--db-border-base)', borderRadius: 4, padding: 8 }}>
          <summary style={{ cursor: 'pointer', display: 'flex', gap: 8, alignItems: 'center', flexWrap: 'wrap' }}>
            <Tag componentId="gsb.designer.test_status" color={RESULT_TAG[r.status].color}>
              {RESULT_TAG[r.status].label}
            </Tag>
            <Typography.Text bold>{r.name}</Typography.Text>
            <Typography.Text>{r.detail}</Typography.Text>
          </summary>
          <div style={{ display: 'flex', flexDirection: 'column', gap: 8, marginTop: 8 }}>
            <SqlBlock label="Query on the metric view" sql={r.measureSql} />
            {r.expandedSql && <SqlBlock label="The SQL the engine would produce" sql={r.expandedSql} />}
          </div>
        </details>
      ))}
    </div>
  );
}

function Designer({
  data,
  onChange,
}: {
  data: DesignerView & { draft: DesignDraft };
  onChange: (v: DesignerView) => void;
}) {
  const { projectId = '' } = useParams();
  const { draft } = data;
  const [yaml, setYaml] = useState(draft.yaml);
  const [instruction, setInstruction] = useState('');
  const [busy, setBusy] = useState<'save' | 'refine' | 'generate' | 'plan' | 'validate'>();
  const [plan, setPlan] = useState<ValidationPlan>();
  const [error, setError] = useState<string>();
  const dirty = yaml !== draft.yaml;

  const live = useMemo(() => validateMetricView(yaml), [yaml]);
  const saved = useMemo(() => validateMetricView(draft.yaml).view, [draft.yaml]);
  const issues = dirty ? live.issues : draft.issues;
  const view = live.view ?? saved;

  const run = (kind: 'save' | 'refine' | 'generate' | 'validate', path: string, body: unknown) => {
    setBusy(kind);
    setError(undefined);
    api<DesignerView>(path, body).then(
      (v) => {
        setBusy(undefined);
        setInstruction('');
        setPlan(undefined);
        if (v.draft) setYaml(v.draft.yaml);
        onChange(v);
      },
      (err: unknown) => {
        setBusy(undefined);
        setError((err as Error).message);
      }
    );
  };

  return (
    <div style={{ display: 'flex', flexDirection: 'column', gap: 16 }}>
      <div style={{ display: 'flex', alignItems: 'center', gap: 8, flexWrap: 'wrap' }}>
        <Typography.Text bold>
          {draft.name}, version {draft.version}
        </Typography.Text>
        <Tag componentId="gsb.designer.origin">{ORIGIN[draft.origin]}</Tag>
        <Tag componentId="gsb.designer.status" color={draft.status === 'validated' ? 'teal' : 'lemon'}>
          {draft.status === 'validated' ? 'Validated' : 'Not validated'}
        </Tag>
        {dirty && <Tag componentId="gsb.designer.dirty">Unsaved changes</Tag>}
      </div>
      {draft.origin !== 'edited' && (
        <Alert
          componentId="gsb.designer.ai_notice"
          type="info"
          closable={false}
          message="Designed by AI. Review the joins and every measure before you validate."
          description={draft.explanations.summary}
        />
      )}
      {error && <Alert componentId="gsb.designer.error" type="error" closable={false} message={error} />}

      <div style={{ display: 'flex', gap: 24, flexWrap: 'wrap', alignItems: 'flex-start' }}>
        <section
          aria-labelledby="gsb-designer-yaml-label"
          style={{ flex: '1 1 420px', minWidth: 0, display: 'flex', flexDirection: 'column', gap: 8 }}
        >
          <FormUI.Label htmlFor="gsb-designer-yaml" id="gsb-designer-yaml-label">
            Metric view YAML
          </FormUI.Label>
          <YamlEditor value={yaml} onChange={setYaml} />
          <div style={{ display: 'flex', gap: 8 }}>
            <Button
              componentId="gsb.designer.save"
              type="primary"
              loading={busy === 'save'}
              disabled={!dirty || !!busy}
              onClick={() => run('save', `/api/projects/${projectId}/designs`, { baseVersion: draft.version, yaml })}
            >
              Save version
            </Button>
            <Button componentId="gsb.designer.discard" disabled={!dirty || !!busy} onClick={() => setYaml(draft.yaml)}>
              Discard changes
            </Button>
          </div>
          <Issues issues={issues} live={dirty} />
        </section>

        <section
          aria-labelledby="gsb-designer-model"
          style={{ flex: '1 1 420px', minWidth: 0, display: 'flex', flexDirection: 'column', gap: 12 }}
        >
          <Typography.Title level={3} id="gsb-designer-model" withoutMargins>
            Model
          </Typography.Title>
          {view ? (
            <>
              <JoinDiagram view={view} issues={issues} />
              <Fields draft={draft} view={view} />
            </>
          ) : (
            <Typography.Text color="secondary">Fix the YAML errors to see the model.</Typography.Text>
          )}
        </section>
      </div>

      <section aria-labelledby="gsb-designer-tests" style={{ display: 'flex', flexDirection: 'column', gap: 8 }}>
        <Typography.Title level={3} id="gsb-designer-tests" withoutMargins>
          Test cases
        </Typography.Title>
        <Typography.Text color="secondary">
          Validation creates the metric view in the sandbox schema, runs each test as you, and compares the result with
          plain SQL derived from the YAML.
        </Typography.Text>
        {draft.tests.length ? (
          <ul style={{ margin: 0, paddingLeft: 20 }}>
            {draft.tests.map((t) => (
              <li key={t.name}>
                <Typography.Text bold>{t.name}</Typography.Text>: {t.measures.join(', ')}
                {t.dimensions.length ? ` by ${t.dimensions.join(', ')}` : ' in total'}
              </li>
            ))}
          </ul>
        ) : (
          <Typography.Text>No test cases match the current fields.</Typography.Text>
        )}
        <div>
          <Button
            componentId="gsb.designer.validate"
            type="primary"
            loading={busy === 'plan' || busy === 'validate'}
            disabled={dirty || !!busy || !draft.tests.length || draft.issues.some((i) => i.severity === 'error')}
            onClick={() => {
              setBusy('plan');
              setError(undefined);
              api<ValidationPlan>(`/api/projects/${projectId}/designs/${draft.version}/validation`).then(
                (p) => {
                  setBusy(undefined);
                  setPlan(p);
                },
                (err: unknown) => {
                  setBusy(undefined);
                  setError((err as Error).message);
                }
              );
            }}
          >
            Validate in sandbox
          </Button>
        </div>
        {busy === 'validate' && (
          <div role="status">
            <Typography.Text color="secondary">Creating the sandbox view and running the tests.</Typography.Text>
          </div>
        )}
        {data.validation && <ValidationResults run={data.validation} />}
      </section>

      <Modal
        componentId="gsb.designer.validate_modal"
        title="Validate in sandbox"
        visible={!!plan}
        okText="Run SQL"
        cancelText="Cancel"
        okButtonProps={{ loading: busy === 'validate' }}
        onCancel={() => setPlan(undefined)}
        onOk={() => {
          if (plan)
            run('validate', `/api/projects/${projectId}/designs/${draft.version}/validation`, {
              statements: plan.statements,
            });
        }}
      >
        {plan && (
          <div style={{ display: 'flex', flexDirection: 'column', gap: 12 }}>
            <Alert
              componentId="gsb.designer.validate_warning"
              type="warning"
              closable={false}
              message={`This SQL runs as you and creates or replaces the metric view ${plan.sandboxView}. Then ${draft.tests.length} read-only test queries run. Result values are not stored.`}
            />
            {plan.statements.map((s) => (
              <SqlBlock key={s} label="SQL to run" sql={s} />
            ))}
          </div>
        )}
      </Modal>

      <div style={{ display: 'flex', flexDirection: 'column', gap: 8, maxWidth: 720 }}>
        <FormUI.Label htmlFor="gsb-designer-refine">Ask for a change</FormUI.Label>
        <Input.TextArea
          componentId="gsb.designer.refine_input"
          id="gsb-designer-refine"
          value={instruction}
          autoSize={{ minRows: 2, maxRows: 6 }}
          placeholder="For example: add a gross margin measure and a ship year dimension."
          onChange={(e) => setInstruction(e.target.value)}
        />
        {dirty && <FormUI.Hint>Save or discard your edits before you ask the AI for a change.</FormUI.Hint>}
        <div style={{ display: 'flex', gap: 8 }}>
          <Button
            componentId="gsb.designer.refine"
            loading={busy === 'refine'}
            disabled={dirty || instruction.trim().length < 3 || !!busy}
            onClick={() => run('refine', `/api/projects/${projectId}/designs/refine`, { instruction })}
          >
            Apply change
          </Button>
          <Button
            componentId="gsb.designer.regenerate"
            loading={busy === 'generate'}
            disabled={dirty || !!busy}
            onClick={() => run('generate', `/api/projects/${projectId}/designs/generate`, {})}
          >
            Generate a new design
          </Button>
        </div>
        {(busy === 'refine' || busy === 'generate') && (
          <div role="status">
            <Typography.Text color="secondary">
              Reading the tables and designing. This can take a minute.
            </Typography.Text>
          </div>
        )}
      </div>

      <Typography.Text color="secondary">
        {data.history.length} version{data.history.length === 1 ? '' : 's'}. Every save and AI change adds a version.
      </Typography.Text>
    </div>
  );
}

export function DesignerPage() {
  const { projectId = '' } = useParams();
  const view = useResource<DesignerView>(`/api/projects/${projectId}/designs`);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string>();
  const data = view.data;

  const generate = () => {
    setBusy(true);
    setError(undefined);
    api<DesignerView>(`/api/projects/${projectId}/designs/generate`, {}).then(
      (v) => {
        setBusy(false);
        view.setData(v);
      },
      (err: unknown) => {
        setBusy(false);
        setError((err as Error).message);
      }
    );
  };

  return (
    <DataState status={view.status} message={view.error} onRetry={view.reload}>
      {data?.draft ? (
        <Designer key={data.draft.version} data={{ ...data, draft: data.draft }} onChange={view.setData} />
      ) : (
        <div style={{ display: 'flex', flexDirection: 'column', gap: 12, alignItems: 'center' }}>
          <Empty
            title="No metric view yet"
            description="The AI designs a metric view from the confirmed brief and the profiled source tables. It reads metadata only, with your permissions."
            button={
              <Button componentId="gsb.designer.generate" type="primary" loading={busy} onClick={generate}>
                Generate design
              </Button>
            }
          />
          {busy && (
            <div role="status">
              <Typography.Text color="secondary">
                Reading the tables and designing. This can take a minute.
              </Typography.Text>
            </div>
          )}
          {error && <Alert componentId="gsb.designer.error" type="error" closable={false} message={error} />}
        </div>
      )}
    </DataState>
  );
}
